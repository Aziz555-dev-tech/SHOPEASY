/**
 * Get translation for a given key
 * @param {string} key - Translation key (e.g., 'nav.home')
 * @param {string} lang - Language code
 * @returns {string} Translated text
 */
export function t(key, lang = 'fr') {
    const keys = key.split('.');
    let value = translations[lang];
    
    for (const k of keys) {
        if (value && typeof value === 'object') {
            value = value[k];
        } else {
            return key; // Return key if translation not found
        }
    }
    
    return value || key;
}

/**
 * Get current language from localStorage
 * @returns {string} Current language code
 */
export function getCurrentLanguage() {
    return localStorage.getItem('language') || 'fr';
}

/**
 * Set current language
 * @param {string} lang - Language code
 */
export function setLanguage(lang) {
    localStorage.setItem('language', lang);
    updatePageTranslations(lang);
}

/**
 * Update all text content on the page with translations
 * @param {string} lang - Language code
 */
export function updatePageTranslations(lang) {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        element.textContent = t(key, lang);
    });
    
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        element.placeholder = t(key, lang);
    });
    
    document.querySelectorAll('[data-i18n-title]').forEach(element => {
        const key = element.getAttribute('data-i18n-title');
        element.title = t(key, lang);
    });
}